"""Deterministic offline paper book; provided quotes only, no external orders.

Signals are target weights, not forecasts generated by this module. Quotes are
filled at their supplied bid/ask without pretending to model depth or latency.
Funding belongs to the existing position before a rebalance. A stopped book
liquidates only against fresh quotes; stale residual positions remain visible.
"""

import hashlib
import json
import math


PLAN_FIELDS = {"protocol_id", "initial_cash", "max_gross_fraction",
               "max_asset_fraction", "fee_bps", "max_drawdown_fraction",
               "max_quote_age_s", "allowed_assets"}
EVENT_FIELDS = {"key", "ts", "asset", "bid", "ask", "quote_ts", "signal", "avail_ts"}
TMAX = 4102444800


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, allow_nan=False)


def _finite(value):
    if type(value) not in (int, float):
        return False
    try:
        return math.isfinite(value)
    except OverflowError:
        return False


def _time(value):
    return type(value) is int and 0 <= value <= TMAX


def _plan_errors(plan):
    if not isinstance(plan, dict):
        return [{"code": "BAD_TYPE", "path": "plan"}]
    errors = []
    for key in sorted(PLAN_FIELDS - plan.keys()):
        errors.append(dict(code="MISSING_FIELD", path="plan." + key))
    for key in sorted(plan.keys() - PLAN_FIELDS, key=str):
        errors.append(dict(code="UNKNOWN_FIELD", path="plan." + str(key)))
    if errors:
        return errors
    if not isinstance(plan["protocol_id"], str) or not plan["protocol_id"]:
        errors.append(dict(code="BAD_VALUE", path="plan.protocol_id"))
    for key in ("initial_cash", "max_gross_fraction", "max_asset_fraction",
                "fee_bps", "max_drawdown_fraction"):
        if not _finite(plan[key]):
            errors.append(dict(code="BAD_VALUE", path="plan." + key))
    if errors:
        return errors
    tests = {
        "initial_cash": plan["initial_cash"] > 0,
        "max_gross_fraction": 0 < plan["max_gross_fraction"] <= 1,
        "max_asset_fraction": 0 < plan["max_asset_fraction"] <= plan["max_gross_fraction"],
        "fee_bps": plan["fee_bps"] >= 0,
        "max_drawdown_fraction": 0 < plan["max_drawdown_fraction"] < 1,
        "max_quote_age_s": type(plan["max_quote_age_s"]) is int and plan["max_quote_age_s"] >= 0,
        "allowed_assets": (isinstance(plan["allowed_assets"], list)
                           and bool(plan["allowed_assets"])
                           and all(isinstance(a, str) and a for a in plan["allowed_assets"])
                           and len(set(plan["allowed_assets"])) == len(plan["allowed_assets"]))}
    errors.extend(dict(code="BAD_VALUE", path="plan." + key)
                  for key, good in tests.items() if not good)
    return errors


def _event_error(event, allowed, now):
    if not isinstance(event, dict):
        return "BAD_EVENT_TYPE"
    if not EVENT_FIELDS <= event.keys():
        return "MISSING_EVENT_FIELD"
    if event.keys() - EVENT_FIELDS - {"funding_rate"}:
        return "UNKNOWN_EVENT_FIELD"
    if not isinstance(event["key"], str) or not event["key"]:
        return "BAD_KEY"
    if not isinstance(event["asset"], str) or event["asset"] not in allowed:
        return "UNKNOWN_ASSET"
    if not all(_time(event[key]) for key in ("ts", "quote_ts", "avail_ts")):
        return "BAD_TIME"
    if now is not None and event["ts"] < now:
        return "OUT_OF_ORDER"
    if not all(_finite(event[key]) for key in ("bid", "ask", "signal")):
        return "NONFINITE_EVENT"
    if event["bid"] <= 0 or event["ask"] < event["bid"]:
        return "BAD_QUOTE"
    if not -1 <= event["signal"] <= 1:
        return "BAD_SIGNAL"
    if "funding_rate" in event and not _finite(event["funding_rate"]):
        return "BAD_FUNDING"
    if event["quote_ts"] > event["ts"]:
        return "FUTURE_QUOTE"
    if event["avail_ts"] > event["ts"]:
        return "LOOKAHEAD_SIGNAL"
    return None


def simulate_paper(plan: dict, events: list[dict]) -> dict:
    """Replay from scratch with no I/O or mutation of the provided arguments."""
    errors = _plan_errors(plan)
    if not isinstance(events, list):
        errors.append(dict(code="BAD_TYPE", path="events"))
    protocol_id = plan.get("protocol_id") if isinstance(plan, dict) else None
    if errors:
        return dict(status="INVALID_INPUT", source_mode="paper_simulation",
                    protocol_id=protocol_id, errors=errors)
    try:
        return _simulate(plan, events)
    except (OverflowError, ZeroDivisionError, ValueError):
        return dict(status="NUMERIC_ERROR", source_mode="paper_simulation",
                    protocol_id=protocol_id,
                    errors=[dict(code="NUMERIC_OVERFLOW", path="simulation")])


def _simulate(plan, events):
    cash = float(plan["initial_cash"])
    positions, quotes, accepted = {}, {}, {}
    fills, errors, audit, fees, funding_costs, breaches = [], [], [], [], [], []
    head, last_time = "0" * 64, None
    peak, max_drawdown, stopped = cash, 0.0, False
    stop_reasons = []
    hits, accepted_events = 0, 0
    fee_rate = plan["fee_bps"] / 10000

    def finite(value):
        if not _finite(value):
            raise ValueError("non-finite simulated book")
        return value

    def mark(asset):
        quote = quotes[asset]
        return finite(quote["bid"] / 2 + quote["ask"] / 2)

    def equity(book=None, balance=None):
        book = positions if book is None else book
        balance = cash if balance is None else balance
        return finite(math.fsum([balance, *(units * mark(asset) for asset, units in sorted(book.items()))]))

    def limits(book, balance):
        value = equity(book, balance)
        if value <= 0:
            return False
        notionals = [abs(units * mark(asset)) for asset, units in sorted(book.items())]
        return (math.fsum(notionals) <= plan["max_gross_fraction"] * value
                and all(n <= plan["max_asset_fraction"] * value for n in notionals))

    def drawdown():
        nonlocal peak, max_drawdown
        value = equity()
        peak = max(peak, value)
        observed = max(0.0, (peak - value) / peak)
        max_drawdown = max(max_drawdown, observed)
        return observed

    def stop(reason, ts):
        nonlocal stopped
        stopped = True
        if reason not in stop_reasons:
            stop_reasons.append(reason)
            breaches.append(dict(ts=ts, reason=reason, equity=equity()))

    def append_audit(index, event, outcome, details=None):
        nonlocal head
        try:
            payload_hash = hashlib.sha256(_canonical(event).encode()).hexdigest()
        except (TypeError, ValueError):
            payload_hash = None
        book_hash = hashlib.sha256(_canonical(dict(cash=cash, positions=positions,
                                                   quotes=quotes)).encode()).hexdigest()
        post = dict(seq=len(audit), index=index, key=event.get("key") if isinstance(event, dict) else None,
                    ts=event.get("ts") if isinstance(event, dict) and _time(event.get("ts")) else None,
                    outcome=outcome, payload_sha256=payload_hash, book_sha256=book_hash, prev=head)
        if details is not None:
            post["details"] = details
        head = hashlib.sha256(_canonical(post).encode()).hexdigest()
        audit.append(dict(post, hash=head))

    def execute(asset, target_units, ts, key, reason):
        nonlocal cash
        before = positions.get(asset, 0.0)
        delta = finite(target_units - before)
        if delta == 0:
            return
        price = quotes[asset]["ask"] if delta > 0 else quotes[asset]["bid"]
        notional = finite(abs(delta) * price)
        fee = finite(notional * fee_rate)
        cash = finite(cash - delta * price - fee)
        if target_units == 0:
            positions.pop(asset, None)
        else:
            positions[asset] = target_units
        fees.append(fee)
        fills.append(dict(key=key, ts=ts, asset=asset, side="BUY" if delta > 0 else "SELL",
                          units=abs(delta), price=price, fee=fee, reason=reason,
                          units_after=target_units))

    def liquidate(ts, key):
        for asset in sorted(list(positions)):
            if ts - quotes[asset]["quote_ts"] <= plan["max_quote_age_s"]:
                execute(asset, 0.0, ts, key, "RISK_LIQUIDATION")

    for index, event in enumerate(events):
        key = event.get("key") if isinstance(event, dict) else None
        raw = None
        try:
            raw = _canonical(event)
        except (TypeError, ValueError):
            pass
        if isinstance(key, str) and key in accepted:
            if raw == accepted[key]:
                hits += 1
                append_audit(index, event, "IDEMPOTENT_HIT")
            else:
                errors.append(dict(index=index, key=key, code="KEY_CONFLICT"))
                append_audit(index, event, "REJECTED", "KEY_CONFLICT")
            continue
        reason = _event_error(event, plan["allowed_assets"], last_time)
        if reason is None and event["ts"] - event["quote_ts"] > plan["max_quote_age_s"]:
            reason = "STALE_QUOTE"
        if reason is not None or raw is None:
            reason = reason or "NONCANONICAL_EVENT"
            errors.append(dict(index=index, key=key if isinstance(key, str) else None, code=reason))
            append_audit(index, event, "REJECTED", reason)
            continue
        ts, asset = event["ts"], event["asset"]
        last_time = ts
        quotes[asset] = dict(bid=event["bid"], ask=event["ask"], quote_ts=event["quote_ts"])
        payment = finite(positions.get(asset, 0.0) * mark(asset) * event.get("funding_rate", 0))
        cash = finite(cash - payment)
        funding_costs.append(payment)
        accepted[key] = raw
        accepted_events += 1
        if any(ts - quotes[held]["quote_ts"] > plan["max_quote_age_s"] for held in positions):
            stop("STALE_PORTFOLIO_QUOTE", ts)
        if drawdown() >= plan["max_drawdown_fraction"]:
            stop("DRAWDOWN_LIMIT", ts)
        if not limits(positions, cash):
            stop("EXPOSURE_LIMIT_AFTER_MARK", ts)
        if stopped:
            liquidate(ts, key)
            drawdown()
            append_audit(index, event, "RISK_STOPPED")
            continue
        previous = positions.get(asset, 0.0)
        requested = finite(event["signal"] * plan["max_asset_fraction"] * equity() / mark(asset))

        def projected(units):
            delta = finite(units - previous)
            price = event["ask"] if delta > 0 else event["bid"]
            charge = finite(abs(delta) * price * fee_rate)
            balance = finite(cash - delta * price - charge)
            book = dict(positions)
            book[asset] = units
            return book, balance

        target = requested
        book, balance = projected(target)
        clipped = not limits(book, balance)
        if clipped:
            # The feasible set along this trade segment is convex. Keep the
            # feasible lower endpoint, including spread and fees in equity.
            low, high = 0.0, 1.0
            for _ in range(80):
                middle = (low + high) / 2
                units = previous + middle * (requested - previous)
                book, balance = projected(units)
                if limits(book, balance):
                    low = middle
                else:
                    high = middle
            target = previous + low * (requested - previous)
        execute(asset, target, ts, key, "RISK_CAPPED_TARGET" if clipped else "SIGNAL_TARGET")
        if not limits(positions, cash):
            stop("EXPOSURE_LIMIT_AFTER_FILL", ts)
            liquidate(ts, key)
        if drawdown() >= plan["max_drawdown_fraction"]:
            stop("DRAWDOWN_LIMIT", ts)
            liquidate(ts, key)
            drawdown()
        append_audit(index, event, "RISK_STOPPED" if stopped else "ACCEPTED",
                     "target_capped" if clipped else None)

    value = equity()
    result = dict(status="RISK_STOPPED" if stopped else "REJECTED_EVENTS" if errors else "OK",
                  source_mode="paper_simulation", protocol_id=plan["protocol_id"],
                  cash=cash, end_equity=value, peak_equity=peak, max_drawdown=max_drawdown,
                  total_fees=finite(math.fsum(fees)), total_funding=finite(math.fsum(funding_costs)),
                  accepted_events=accepted_events, idempotent_hits=hits, errors=errors,
                  fills=fills, audit=audit, audit_head=head, stopped=stopped,
                  stop_reasons=stop_reasons, risk_breaches=breaches,
                  unliquidated_assets=sorted(positions) if stopped else [],
                  positions={asset: dict(units=units, mark=mark(asset), notional=finite(units * mark(asset)))
                             for asset, units in sorted(positions.items())})
    _canonical(result)
    return result
